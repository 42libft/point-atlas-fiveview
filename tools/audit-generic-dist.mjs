import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { auditDist } from './generic-audit-lib.mjs';
const root = process.env.DIST_ROOT ?? fileURLToPath(new URL('../dist', import.meta.url));
const report = await auditDist(root);
const index = process.argv.indexOf('--report');
if (index !== -1) await writeFile(resolve(process.argv[index + 1]), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ scope: report.scope, passed: report.passed, files: report.files.length, totalBytes: report.totalBytes, issues: report.issues }));
if (!report.passed) process.exitCode = 1;
